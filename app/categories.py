#!/usr/bin/env python3
"""categories.py — один словарь категорий на весь проект.

Зачем. Модель писала категорию свободным текстом: в архиве накопилось 26 разных
значений («парсинг + автоматизация», «настройка Senler, чат-боты, лендинг…»,
«перевод макета CDR в AI»). Для человека это читаемо, для таблицы — мусор:
выпадающий список не совпадёт ни с одним значением, сводная по категориям
развалится на 26 строк по одному заказу.

Решение — фиксированный список из восьми категорий. Он выведен из архива,
а не придуман: каждая из 26 старых записей вручную отнесена к одной из восьми
(таблица ARCHIVE ниже). Модель теперь обязана вернуть одно из восьми, а если
она всё же написала своё — normalize() приводит текст к канону по ключевым
словам, а не оставляет как есть.
"""
from __future__ import annotations

import re

# Канон. Порядок важен только для отчётов: в таблице он станет порядком чипов.
BOTS = "Telegram-боты"
PARSING = "Парсинг и автоматизация"
INTEGRATIONS = "Интеграции и ИИ"
SITES = "Сайты и лендинги"
MARKETING = "Маркетинг и текст"
DESIGN = "Дизайн"
ROUTINE = "Ручная рутина"
OTHER = "Другое"

CATEGORIES = (BOTS, PARSING, INTEGRATIONS, SITES, MARKETING, DESIGN, ROUTINE, OTHER)

# Строка для промпта: модель должна видеть ровно этот перечень.
PROMPT_LINE = ", ".join(f"«{name}»" for name in CATEGORIES)

# Как старый архив ложится на канон. Ключ — то, что реально лежит в базе,
# значение — категория. Таблица ручная: автоматика по ключевым словам ошибается
# на составных заказах («настройка Senler, чат-боты, лендинг» — это маркетинг,
# хотя слово «бот» там есть).
ARCHIVE = {
    # --- боты
    "Telegram-бот": BOTS,
    "Telegram-бот + Google-таблица": BOTS,
    "Telegram-бот на Python с ИИ и видеообработкой": BOTS,
    "Разработка бота/мини-приложения": BOTS,
    "Telegram-автоматизация (userbot)": BOTS,
    # --- парсинг и автоматизация
    "парсинг + автоматизация": PARSING,
    "парсинг и технический аудит": PARSING,
    "автоматизация и парсинг с интеграцией (Яндекс Диск API + Pla": PARSING,
    # --- интеграции и ИИ
    "интеграция AI через API": INTEGRATIONS,
    "интеграция API / Python-разработка с ИИ (бот-ассистент)": INTEGRATIONS,
    # --- маркетинг и текст
    "настройка Senler, чат-боты, лендинг, интеграция платежей": MARKETING,
    "продвижение Telegram-каналов / реклама": MARKETING,
    "привлечение подписчиков/трафик": MARKETING,
    "Яндекс.Директ / реклама (B2B)": MARKETING,
    "новостной SMM / копирайтинг для Telegram": MARKETING,
    "SEO/GEO-копирайтинг, статьи": MARKETING,
    # --- дизайн
    "дизайн (иконки, бейджи, аватарки в Figma)": DESIGN,
    "перевод макета CDR в AI (векторная графика)": DESIGN,
    "3D-моделирование в Blender (ассеты для Unity)": DESIGN,
    # --- ручная рутина
    "заполнение товарных карт / операторский ввод данных": ROUTINE,
    "заполнение карточек товаров (операторская работа)": ROUTINE,
    "заполнение анкет вручную": ROUTINE,
    "Массовый инвайтинг пользователей в Telegram-чат": ROUTINE,
    "участие в онлайн-чате/комьюнити": ROUTINE,
    # --- не наше
    "разработка регламентов и базы знаний": OTHER,
    "сценарий и AI-видео для ребёнка": OTHER,
}

# Запасной путь: если модель написала текст, которого нет в ARCHIVE, решаем по
# ключевым словам. Порядок проверок важен — первое совпадение выигрывает.
# Ручная рутина стоит первой: «массовый инвайтинг в Telegram» содержит «telegram»,
# но это не разработка.
RULES = (
    (ROUTINE, r"инвайт|заполнен|карточк|анкет|оператор|вручную|комьюнити|модерац|"
              r"выкладк|копипаст|рерайт"),
    (MARKETING, r"реклам|продвижен|подписчик|трафик|\bsmm\b|\bseo\b|копирайт|директ|"
                r"senler|рассылк|маркет|таргет|контент-план"),
    (DESIGN, r"дизайн|figma|макет|вектор|\b3d\b|blender|иконк|аватар|брендинг|"
             r"иллюстрац|презентац"),
    (BOTS, r"телеграм-бот|тг-бот|чат-бот|\bбот\b|бот[а-я]* на|userbot|мини-приложен|"
           r"миниприложен|webapp"),
    (PARSING, r"парс|сбор данн|выгрузк|скрипт|автоматизац|бот[а-я]* для|"
              r"гугл-таблиц|google-таблиц|excel"),
    (INTEGRATIONS, r"интеграц|\bapi\b|\bllm\b|нейросет|\bgpt\b|openai|\bии\b|\bai\b|"
                   r"crm|amocrm|битрикс"),
    (SITES, r"сайт|лендинг|верстк|wordpress|tilda|тильда|cms|интернет-магазин|"
            r"магазин на"),
)

_WS = re.compile(r"\s+")


def _clean(raw) -> str:
    """Привести вход к сравнимому виду: без лишних пробелов, нижний регистр."""
    return _WS.sub(" ", str(raw or "")).strip()


def normalize(raw) -> str:
    """Свободный текст → одна из восьми категорий. Неизвестное — «Другое».

    Три пути по порядку:
      1. уже канон (модель послушалась промпта) — вернуть как есть, с точным
         написанием;
      2. есть в таблице архива — вернуть её значение;
      3. есть ключевое слово — вернуть категорию по правилу.
    Пустая строка и мусор дают «Другое», а не пустую ячейку: пустая категория
    в таблице выглядит как сбой, а «Другое» — как честный ответ.
    """
    text = _clean(raw)
    if not text:
        return OTHER
    low = text.lower()

    for name in CATEGORIES:
        if low == name.lower():
            return name
    if text in ARCHIVE:
        return ARCHIVE[text]
    if low in ARCHIVE:
        return ARCHIVE[low]
    # Старые значения в базе обрезались до 60 символов и иногда оканчиваются на
    # полуслове. Если точного совпадения нет, ищем ключ, который начинается с
    # этого текста или наоборот — так обрезанный хвост всё равно попадёт в канон.
    for key, name in ARCHIVE.items():
        if key.startswith(text) or text.startswith(key):
            return name

    for name, pattern in RULES:
        if re.search(pattern, low):
            return name
    return OTHER
