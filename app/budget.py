#!/usr/bin/env python3
"""budget.py — одно правило про бюджет на весь проект.

Почему отдельным файлом. «Есть ли у заказа бюджет» решают два места: правило лида
(`monitor.is_lead`) и выборка строк для Google Таблицы (`storage.sheet_pending`).
Раньше правило жило только в первом, а таблица брала всё подряд — и строка без
суммы уезжала в таблицу, хотя владелец сказал «без бюджета не берём». Пока
функция одна, разъехаться эти два места не могут: оба зовут pick_budget.

Модель отдаёт бюджет словами («5 000 ₽», «от 15 000», «по договорённости»),
а цена объявления приходит числом или отсутствует вовсе (у части лент цены нет).
Поэтому: берём первое число из текста модели; нет числа — берём цену объявления;
нет ни там, ни там — бюджета нет.
"""
from __future__ import annotations

import re

DIGITS_RE = re.compile(r"\d[\d\s]*")   # первое число в текстовом бюджете


def budget_value(text):
    """Бюджет числом, если в тексте есть цифры. Иначе — пустая строка.

    Зачем не отдавать текст как есть: чужой скрипт таблицы делает
    `Number(data.budget) || 0`, и «5 000 ₽» превращается в ноль. Тогда сводные
    «суммарный бюджет» и «средний чек» показывают нули, выглядя рабочими.
    """
    found = DIGITS_RE.search(str(text or ""))
    if not found:
        return ""
    return int(re.sub(r"\s", "", found.group(0)))


def pick_budget(budget, price):
    """Что писать в «Бюджет»: число из ответа модели, иначе цену объявления.

    Пустая строка означает «бюджета нет» — и это не «ноль», а решение не брать
    заказ. Живой случай, из которого правило выросло: модель написала «не указан
    (просит предложить цену)», текст непустой и перебивал реальные 15 000 ₽ из
    объявления. Теперь текст без цифр бюджетом не считается.
    """
    number = budget_value(budget)
    if number != "":
        return number
    return budget_value(price)


def has_budget(budget, price) -> bool:
    """Есть ли сумма. Короткая форма для условий — читается лучше сравнения с ""."""
    return pick_budget(budget, price) != ""
